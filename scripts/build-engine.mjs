// Bundles pdf.js, JSZip and engine/engine.js into a single offline HTML string for the extractor WebView.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

function toClassicScript(src, name) {
  const out = src
    .replace(/export\s*\{[^}]*\}\s*;?\s*$/, '')
    .replaceAll('import.meta.url', '"file:///"');
  if (out.includes('import.meta')) throw new Error(`${name}: import.meta still present`);
  if (/<\/script/i.test(out)) throw new Error(`${name}: contains </script`);
  // Minified libraries reuse top-level names; classic scripts share one global scope, so isolate each.
  return `(function(){\n${out}\n}).call(globalThis);`;
}

const pdf = toClassicScript(read('node_modules/pdfjs-dist/legacy/build/pdf.min.mjs'), 'pdf');
const worker = toClassicScript(read('node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs'), 'pdf.worker');
const jszip = toClassicScript(read('node_modules/jszip/dist/jszip.min.js'), 'jszip');
const engine = toClassicScript(read('engine/engine.js'), 'engine');

const html = `<!doctype html><html><head><meta charset="utf-8"></head><body>
<script>${jszip}</script>
<script>${worker}</script>
<script>${pdf}</script>
<script>${engine}</script>
</body></html>`;

const outFile = join(root, 'src/engine/engineHtml.generated.ts');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `// Generated by scripts/build-engine.mjs — do not edit.\nexport const ENGINE_HTML = ${JSON.stringify(html)};\n`);
console.log(`engine html: ${(html.length / 1024 / 1024).toFixed(2)} MB`);
