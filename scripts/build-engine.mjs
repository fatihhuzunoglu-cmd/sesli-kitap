// Bundles pdf.js, JSZip, Tesseract, mammoth, foliate's MOBI reader and engine/engine.js into a single offline HTML string for the extractor WebView.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

function toClassicScript(src, name) {
  const out = src
    .replace(/export\s*\{[^}]*\}\s*;?\s*$/, '')
    .replaceAll('import.meta.url', '"file:///"');
  if (out.includes('import.meta')) throw new Error(`${name}: import.meta still present`);
  if (/<\/script/i.test(out)) throw new Error(`${name}: contains </script`);
  // Minified libraries reuse top-level names; classic scripts share one global scope, so isolate each.
  return `(function(){\n${out}\n}).call(globalThis);`;
}

// Older Android WebViews (e.g. 113) lack features pdf.js relies on, such as Promise.withResolvers.
const polyfills = toClassicScript(read('node_modules/core-js-bundle/minified.js'), 'core-js');
const pdf = toClassicScript(read('node_modules/pdfjs-dist/legacy/build/pdf.min.mjs'), 'pdf');
const worker = toClassicScript(read('node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs'), 'pdf.worker');
const jszip = toClassicScript(read('node_modules/jszip/dist/jszip.min.js'), 'jszip');
const tesseract = toClassicScript(read('node_modules/tesseract.js/dist/tesseract.min.js'), 'tesseract');
const mammoth = toClassicScript(read('node_modules/mammoth/mammoth.browser.min.js'), 'mammoth');
// foliate-js mobi.js (MIT, vendored) is an ES module with inline exports; expose its MOBI class as a global instead.
const mobi = toClassicScript(
  read('engine/vendor/mobi.js').replace(/^export (?=(const|class|function|async function) )/gm, '') + '\nglobalThis.FoliateMOBI = MOBI;\n',
  'mobi',
);
const engine = toClassicScript(read('engine/engine.js'), 'engine');
// pdf.js decodes JBIG2 (most scanned books) and JPEG 2000 page images, and ICC colours, with WebAssembly it would normally download.
const pdfWasm = Object.fromEntries(
  ['jbig2.wasm', 'openjpeg.wasm', 'qcms_bg.wasm'].map((f) => [f, readFileSync(join(root, 'node_modules/pdfjs-dist/wasm', f)).toString('base64')]),
);

const html = `<!doctype html><html><head><meta charset="utf-8"></head><body>
<script>globalThis.__pdfWasm=${JSON.stringify(pdfWasm)};</script>
<script>${polyfills}</script>
<script>${jszip}</script>
<script>${tesseract}</script>
<script>${worker}</script>
<script>${pdf}</script>
<script>${mammoth}</script>
<script>${mobi}</script>
<script>${engine}</script>
</body></html>`;

const outFile = join(root, 'src/engine/engineHtml.generated.ts');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `// Generated by scripts/build-engine.mjs — do not edit.\nexport const ENGINE_HTML = ${JSON.stringify(html)};\n`);
console.log(`engine html: ${(html.length / 1024 / 1024).toFixed(2)} MB`);

// OCR runtime and language data stay out of the HTML; the app hands them to the engine only when a book needs OCR.
const ocrDir = join(root, 'assets/ocr');
mkdirSync(ocrDir, { recursive: true });
const ocrAssets = {
  'core.bin': 'node_modules/tesseract.js-core/tesseract-core-simd-lstm.wasm.js',
  'worker.bin': 'node_modules/tesseract.js/dist/worker.min.js',
  'tur.bin': 'node_modules/@tesseract.js-data/tur/4.0.0_best_int/tur.traineddata.gz',
  'eng.bin': 'node_modules/@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz',
};
for (const [name, src] of Object.entries(ocrAssets)) copyFileSync(join(root, src), join(ocrDir, name));
console.log(`ocr assets: ${Object.keys(ocrAssets).join(', ')}`);
